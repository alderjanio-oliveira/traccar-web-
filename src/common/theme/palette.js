import { grey } from '@mui/material/colors';

const validatedColor = (color) => (/^#([0-9A-Fa-f]{3}){1,2}$/.test(color) ? color : null);

const MOBGOTECH_PRIMARY = '#7e14ff';
const MOBGOTECH_SECONDARY = '#47bfff';

export default (server, darkMode) => ({
  mode: darkMode ? 'dark' : 'light',
  background: {
    default: darkMode ? grey[900] : grey[50],
  },
  primary: {
    main: validatedColor(server?.attributes?.colorPrimary) || MOBGOTECH_PRIMARY,
  },
  secondary: {
    main: validatedColor(server?.attributes?.colorSecondary) || MOBGOTECH_SECONDARY,
  },
  neutral: {
    main: grey[500],
  },
  geometry: {
    main: '#3bb2d0',
  },
  alwaysDark: {
    main: grey[900],
  },
});
